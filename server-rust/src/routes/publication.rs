//! Publication API routes
//!
//! Routes:
//! - POST /api/publication/?websiteId=X - Publish the website
//! - GET /api/publication/publication/status?jobId=X - Where that publication is
//!
//! The editor generates the files and sends them here. Writing them is quick,
//! sending them on and waiting for a build is not, and an HTTP request held
//! open for minutes is one a proxy or a laptop lid closes. So publishing
//! answers a job straight away and the editor asks about it every couple of
//! seconds, which is the contract it was written against.
//!
//! The doubled path of the status route is not a mistake: the editor builds it
//! out of `/publication` and `/publication/status`, and the hosted server
//! answers it there too.

use axum::extract::{Query, State};
use axum::routing::{get, post};
use axum::{Json, Router};
use serde::{Deserialize, Serialize};

use crate::error::{Error, Result};
use crate::jobs::{JobData, JobStatus};
use crate::models::{File, Ssg, WebsiteId};
use crate::publish;
use crate::routes::connector::LOCAL_FOLDER;
use crate::routes::AppState;
use crate::storage;

/// Build publication routes
pub fn routes() -> Router<AppState> {
    Router::new()
        .route("/", post(publish_website))
        .route("/publication/status", get(publication_status))
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PublishQuery {
    pub website_id: WebsiteId,

    pub hosting_id: String,

    /// The publication options, as JSON
    ///
    /// The editor encodes everything that is not a string that way. Absent
    /// when the website has no option at all.
    #[serde(default)]
    pub options: Option<String>,
}

impl PublishQuery {
    /// What the editor sent with this publication
    ///
    /// Options nobody could read are no options: publishing matters more than
    /// the address, so it is logged rather than failing the request.
    fn options(&self) -> crate::actions::PublicationOptions {
        let Some(options) = self.options.as_deref() else {
            return Default::default();
        };
        serde_json::from_str(options).unwrap_or_else(|e| {
            tracing::warn!("Could not read the options of the publication: {}", e);
            Default::default()
        })
    }
}

/// Publication request body
///
/// The editor also sends the website data and the publication options, which
/// only a hosting service could use. Serde ignores them, but for the
/// generator the files were made for.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PublishRequest {
    #[serde(default)]
    pub files: Vec<ClientSideFile>,

    #[serde(default)]
    pub settings: PublishedSettings,
}

#[derive(Debug, Default, Deserialize)]
pub struct PublishedSettings {
    #[serde(default)]
    pub ssg: Option<Ssg>,
}

/// A file generated by the editor
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClientSideFile {
    /// Path where the file is published
    pub path: String,

    /// Pretty path taking precedence over `path`, when the editor's permalink
    /// plugin rewrites URLs (e.g. `/about` instead of `/about.html`)
    #[serde(default)]
    pub permalink: Option<String>,

    /// File content, for the files the editor generates
    #[serde(default)]
    pub content: Option<String>,

    /// Path of a stored asset, for the files the editor references
    #[serde(default)]
    pub src: Option<String>,
}

/// What publishing answers, the moment the files are written
#[derive(Debug, Serialize)]
pub struct PublishResponse {
    /// Where the website is served
    ///
    /// Always null here, and kept because `{ url, job }` is what the editor's
    /// own type says. Where the files end up is what the job says.
    pub url: Option<String>,
    pub job: JobData,
}

/// Which publication the editor is asking about
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StatusQuery {
    pub job_id: String,
}

/// Publish a website
///
/// POST /api/publication/?websiteId=X
async fn publish_website(
    State(state): State<AppState>,
    Query(query): Query<PublishQuery>,
    Json(request): Json<PublishRequest>,
) -> Result<Json<PublishResponse>> {
    let mut files: Vec<File> = Vec::new();
    let ssg = request.settings.ssg;

    for file in request.files {
        let content = match (file.content, file.src) {
            (Some(content), _) => content.into_bytes(),
            (None, Some(src)) => {
                let asset_name = asset_name_of(&src);
                storage::read_asset(&state.data_path, &query.website_id, &asset_name).await?
            }
            (None, None) => {
                return Err(Error::InvalidInput(format!(
                    "Silex could not read the file '{}' of your website: it has nothing in it and points at nothing.",
                    file.path
                )))
            }
        };

        files.push(File {
            path: file.permalink.unwrap_or(file.path),
            content,
        });
    }

    publish::publish(&state.data_path, &query.website_id, &files).await?;

    // The files are written, which is the one thing that can be promised
    // here. Whoever takes them further says the rest through the job.
    let job = state
        .jobs
        .start(publishing_message(&state.data_path, &query.website_id));
    let answered = state
        .jobs
        .read(job.id())
        .expect("the publication was just opened");

    match state.actions.clone() {
        Some(actions) => {
            let website_id = query.website_id.clone();
            let local = query.hosting_id == LOCAL_FOLDER;
            let options = crate::actions::PublicationOptions {
                ssg,
                no_ci: local,
                ..query.options()
            };
            let data_path = state.data_path.clone();
            // Building and sending a website both take their time, on a thread
            // of their own so that the server answers meanwhile
            tokio::task::spawn_blocking(move || {
                let publishing = std::panic::AssertUnwindSafe(|| {
                    let built = match actions.build(website_id.as_str(), &options, &job) {
                        Ok(built) => built,
                        Err(message) => return job.failed(message),
                    };
                    if !local {
                        actions.deploy(website_id.as_str(), &options, &job);
                    }
                    // A host that returned without saying how it went leaves the
                    // publication where it really is rather than open forever
                    let mut message = match built {
                        Some(folder) => built_message(&folder),
                        None => published_message(&data_path, &website_id),
                    };
                    // A website written on this computer only, until it has a hosting
                    if local {
                        if let Some(more) = actions.more_hostings() {
                            message.push_str(&format!("<p>{more}</p>"));
                        }
                    }
                    job.succeeded(message);
                });
                if std::panic::catch_unwind(publishing).is_err() {
                    job.failed(crate::message::told(
                        "Silex stopped before the end of the publication.",
                        &[],
                    ));
                }
            });
        }
        None => job.succeeded(published_message(&state.data_path, &query.website_id)),
    }

    Ok(Json(PublishResponse {
        url: None,
        job: answered,
    }))
}

/// What the user reads while nobody has said anything yet
fn publishing_message(data_path: &std::path::Path, website_id: &WebsiteId) -> String {
    told(
        "Publishing your website",
        &crate::storage::published_files_url(data_path, website_id),
    )
}

/// What the user reads when the files are all there is to say
///
/// Not a website that is online: nothing here sent it anywhere.
fn published_message(data_path: &std::path::Path, website_id: &WebsiteId) -> String {
    told(
        "Your website is written on this computer.",
        &crate::storage::published_files_url(data_path, website_id),
    )
}

fn built_message(folder: &std::path::Path) -> String {
    told(
        "Your website is built on this computer.",
        &format!("file://{}", folder.display()),
    )
}

/// A sentence, and the one button this server can offer with it
///
/// It opens the files the editor generated, which may not even have an
/// `index.html` among them, so it never says the published website.
fn told(sentence: &str, files: &str) -> String {
    crate::message::told(
        sentence,
        &[crate::message::Button::secondary(
            crate::message::FILES_ON_THIS_COMPUTER,
            files,
        )],
    )
}

/// Where a publication is
///
/// GET /api/publication/publication/status?jobId=X
async fn publication_status(
    State(state): State<AppState>,
    Query(query): Query<StatusQuery>,
) -> Result<Json<JobData>> {
    // One this server never opened, or opened before being restarted. Either
    // way the editor would ask about it forever.
    let job = state.jobs.read(&query.job_id).unwrap_or_else(|| JobData {
        job_id: query.job_id.clone(),
        status: JobStatus::Error,
        message: "<p>Silex lost track of this publication. Publish again to know how it went.</p>"
            .to_string(),
        logs: vec![Vec::new()],
        errors: vec![Vec::new()],
        start_time: 0,
        end_time: None,
        url: None,
    });
    Ok(Json(job))
}

/// Asset name out of the `src` sent by the editor
///
/// The editor is expected to send a stored path, but it has been seen sending
/// an API path or a full URL. Logged so that we can tell what it really sends
/// and drop this if it turns out to be dead weight.
fn asset_name_of(src: &str) -> String {
    tracing::debug!(src = %src, "publish: reading asset");

    if let Some(pos) = src.find("/api/website/assets/") {
        let after = &src[pos + "/api/website/assets/".len()..];
        return after.split('?').next().unwrap_or(after).to_string();
    }

    if let Some(stripped) = src.strip_prefix("/assets/") {
        return stripped.to_string();
    }

    src.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::Body;
    use axum::http::Request as HttpRequest;
    use std::sync::Arc;
    use tower::ServiceExt;

    struct Panicking;

    impl crate::Actions for Panicking {
        fn build(
            &self,
            _: &str,
            _: &crate::actions::PublicationOptions,
            _: &crate::jobs::Job,
        ) -> std::result::Result<Option<std::path::PathBuf>, String> {
            panic!("a bug of the host application")
        }
    }

    async fn status_of(app: &axum::Router, job_id: &str) -> serde_json::Value {
        let request = HttpRequest::get(format!(
            "/api/publication/publication/status?jobId={job_id}"
        ))
        .body(Body::empty())
        .unwrap();
        let response = app.clone().oneshot(request).await.unwrap();
        let body = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .unwrap();
        serde_json::from_slice(&body).unwrap()
    }

    #[tokio::test]
    async fn a_build_that_panics_ends_the_publication_in_error() {
        let data_path =
            std::env::temp_dir().join(format!("silex-publication-panic-{}", std::process::id()));
        std::fs::create_dir_all(&data_path).unwrap();
        let meta = crate::models::WebsiteMetaFileContent {
            name: "A website".to_string(),
            image_url: None,
        };
        let website_id = storage::create_website(&data_path, &meta).await.unwrap();
        let config = crate::Config::new(data_path).with_actions(Arc::new(Panicking));
        let (app, _) = crate::build_app(config).await;

        let request = HttpRequest::post(format!(
            "/api/publication?websiteId={website_id}&hostingId={LOCAL_FOLDER}"
        ))
        .header("content-type", "application/json")
        .body(Body::from(r#"{"files":[],"settings":{"ssg":"zola"}}"#))
        .unwrap();
        let response = app.clone().oneshot(request).await.unwrap();
        let body = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .unwrap();
        let answer: serde_json::Value = serde_json::from_slice(&body).unwrap();
        let job_id = answer["job"]["jobId"].as_str().unwrap().to_string();

        for _ in 0..100 {
            let job = status_of(&app, &job_id).await;
            if job["status"] != serde_json::to_value(JobStatus::InProgress).unwrap() {
                assert_eq!(
                    job["status"],
                    serde_json::to_value(JobStatus::Error).unwrap()
                );
                return;
            }
            tokio::time::sleep(std::time::Duration::from_millis(20)).await;
        }
        panic!("the publication is still in progress");
    }
}
