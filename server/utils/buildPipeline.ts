import { BuildStep, SsgId } from '~/common/types.js'

export const ELEVENTY_VERSION = '3.1.6'

export const BUILD_JSON_PATH = 'build.json'
export const BUILD_SH_PATH = 'build.sh'
const ZOLA_CONFIG_PATH = 'zola.toml'
// Zola refuses an empty base_url, and a website served at the root of its domain needs no other
const ZOLA_DEFAULT_CONFIG = 'base_url = "/"\n'

export const DEFAULT_BUILD_STEPS: BuildStep[] = [{ type: 'build' }]

// TEMPORARY: remove after the 3.10 stable, only sites published with 3.10.0-canary.3 have this file
const FAIL_ON_CANARY_DATA_FILE = 'test -f public/public.11tydata.js && echo \'Please delete public/public.11tydata.js\' && exit 1'

// || true: sites without images have no assets/ folder in git
const BUILD_COMMANDS = [
  FAIL_ON_CANARY_DATA_FILE,
  `npx @11ty/eleventy@${ELEVENTY_VERSION} --input=public --output=_site`,
  'cp -R public/css public/assets _site/ 2>/dev/null || true',
]

interface Release { x64: { url: string, sha256: string }, arm64: { url: string, sha256: string } }

// Same versions and checksums as desktop/src-tauri/src/generators/zola.rs
const GQLFREEZ: Release = {
  x64: { url: 'https://github.com/lexoyo/gqlfreez/releases/download/v0.2.1/gqlfreez-linux-x64', sha256: 'ece79db164b01802cb98aca6aefb4f411d4c0d33680b845201d851ded658eff0' },
  arm64: { url: 'https://github.com/lexoyo/gqlfreez/releases/download/v0.2.1/gqlfreez-linux-arm64', sha256: '837d0df24f97ae1949b88ff61f933b85ae90ea0f6efb28c3b15f3343005c93fe' },
}
const ZOLA: Release = {
  x64: { url: 'https://github.com/getzola/zola/releases/download/v0.23.6/zola-v0.23.6-x86_64-unknown-linux-musl.tar.gz', sha256: '7d77a4220a4f699cba2fc0e0c7859f780e887e269159ad4fab90e11ea16c906f' },
  arm64: { url: 'https://github.com/getzola/zola/releases/download/v0.23.6/zola-v0.23.6-aarch64-unknown-linux-gnu.tar.gz', sha256: '266448fffbf7c7004ca399d0e76dd699541771096d8a42aede98cebe2a029d02' },
}

// Cached by GitLab CI, where npx keeps its packages
const CACHE_FOLDER = '.npm'
// node, because the build image has neither curl nor wget
const DOWNLOAD = 'node -e "fetch(process.argv[1]).then(r => r.arrayBuffer()).then(b => require(\'fs\').writeFileSync(process.argv[2], Buffer.from(b)))"'

function downloadLines({ x64, arm64 }: Release): string[] {
  return [
    `case "$(uname -m)" in aarch64|arm64) url=${arm64.url} sum=${arm64.sha256} ;; *) url=${x64.url} sum=${x64.sha256} ;; esac`,
    `mkdir -p ${CACHE_FOLDER}`,
    `file=${CACHE_FOLDER}/$(basename "$url")`,
    'if ! echo "$sum  $file" | sha256sum -c - >/dev/null 2>&1; then',
    `  ${DOWNLOAD} "$url" "$file"`,
    '  echo "$sum  $file" | sha256sum -c -',
    'fi',
  ]
}

const ZOLA_BUILD_COMMANDS = [
  // gqlfreez stops on a website without queries, which has no data to fetch
  'if find public -name \'*.graphql\' | grep -q .; then',
  ...[...downloadLines(GQLFREEZ), 'chmod +x "$file"', '"$file" public'].map(line => `  ${line}`),
  'fi',
  // Zola checks the system roots even for local data, and node:22-slim has none
  'if [ ! -e /etc/ssl/certs/ca-certificates.crt ]; then',
  `  mkdir -p ${CACHE_FOLDER}`,
  `  node -e "console.log(require('tls').rootCertificates.join('\\n'))" > ${CACHE_FOLDER}/roots.pem`,
  `  export SSL_CERT_FILE="$PWD/${CACHE_FOLDER}/roots.pem"`,
  'fi',
  ...downloadLines(ZOLA),
  'tar xzf "$file" -C "$(dirname "$file")"',
  // The config is found from the root, the output from here; --force for a _site left by an earlier build
  `"$(dirname "$file")/zola" --root public --config ../${ZOLA_CONFIG_PATH} build --output-dir _site --force`,
]

export function parseBuildSteps(content: string): BuildStep[] {
  const steps = JSON.parse(content)
  if (!Array.isArray(steps)) throw new Error('build.json must be an array of steps')
  steps.forEach((step, i) => {
    if (step?.type === 'build') return
    if (step?.type === 'sh' && typeof step.value === 'string') return
    throw new Error(`build.json step ${i} must be { "type": "build" } or { "type": "sh", "value": "..." }`)
  })
  return steps
}


// Created once, then they belong to the user
export function generatorFiles(ssg?: SsgId): { path: string, content: string }[] {
  return ssg === 'zola' ? [{ path: ZOLA_CONFIG_PATH, content: ZOLA_DEFAULT_CONFIG }] : []
}

export function generateBuildSh(steps: BuildStep[], ssg?: SsgId): string {
  const buildCommands = ssg === 'zola' ? ZOLA_BUILD_COMMANDS : BUILD_COMMANDS
  const lines = steps.flatMap(step => step.type === 'build' ? buildCommands : [step.value])
  return [
    '#!/bin/sh',
    '# Generated by Silex at each publication, do not edit: customize the build in build.json instead',
    'set -e',
    ...lines,
    '',
  ].join('\n')
}
